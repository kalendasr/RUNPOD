import fs from "node:fs";
import path from "node:path";
import { ALL_PAGE_KINDS, pageDef, type PageKind, type WebsiteSpec } from "./types.js";
import { projectDir } from "./paths.js";

function metadataBlock(title: string, description: string): string {
  return `export const metadata: Metadata = {
  title: ${JSON.stringify(title)},
  description: ${JSON.stringify(description)},
};

`;
}

function homePageContent(spec: WebsiteSpec): string {
  const def = pageDef("home", spec.siteName);
  const hasContact = spec.pages.includes("contact");

  const heroBody = hasContact
    ? `    <Hero title=${JSON.stringify(spec.siteName)} subtitle=${JSON.stringify(spec.siteDescription)}>
      <Link
        href="/contact"
        className="inline-flex items-center justify-center rounded-md bg-slate-900 px-4 py-2 text-sm font-medium text-white transition-colors hover:bg-slate-700"
      >
        Get in touch
      </Link>
    </Hero>`
    : `    <Hero title=${JSON.stringify(spec.siteName)} subtitle=${JSON.stringify(spec.siteDescription)} />`;

  return `import type { Metadata } from "next";
import Link from "next/link";
import { Hero } from "@/components/Hero";

${metadataBlock(def.title, def.description)}export default function HomePage() {
  return (
${heroBody}
  );
}
`;
}

