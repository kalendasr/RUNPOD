const CONTENT_BY_KIND: Record<PageKind, (spec: WebsiteSpec) => string> = {
  home: homePageContent,
  about: aboutPageContent,
  services: servicesPageContent,
  projects: projectsPageContent,
  contact: contactPageContent,
};

export function pageFileContent(kind: PageKind, spec: WebsiteSpec): string {
  return CONTENT_BY_KIND[kind](spec);
}

export function siteConfigContent(spec: WebsiteSpec): string {
  const nav = spec.pages.map((kind) => {
    const def = pageDef(kind, spec.siteName);
    return { href: def.slug ? `/${def.slug}` : "/", label: def.navLabel };
  });
  return `// Generated by @hermes/website-factory. Do not edit by hand — regenerate
// via \`hermes-website generate\` instead.
export interface NavLink {
  href: string;
  label: string;
}

export interface SiteConfig {
  name: string;
  description: string;
  nav: NavLink[];
}

export const siteConfig: SiteConfig = ${JSON.stringify(
    { name: spec.siteName, description: spec.siteDescription, nav },
    null,
    2,
  )};
`;
}

export function writePages(spec: WebsiteSpec): void {
  const appDir = path.join(projectDir(spec.projectName), "app");
  const validKinds = spec.pages.filter((kind) => ALL_PAGE_KINDS.includes(kind));

  for (const kind of validKinds) {
    const def = pageDef(kind, spec.siteName);
    const targetDir = def.slug ? path.join(appDir, def.slug) : appDir;
    fs.mkdirSync(targetDir, { recursive: true });
    fs.writeFileSync(path.join(targetDir, "page.tsx"), pageFileContent(kind, spec), "utf8");
  }

  const libDir = path.join(projectDir(spec.projectName), "lib");
  fs.mkdirSync(libDir, { recursive: true });
  fs.writeFileSync(path.join(libDir, "site-config.ts"), siteConfigContent(spec), "utf8");
}
